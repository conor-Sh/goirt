def iter_crops():
    """Yield (crop, group) for every value in the seed taxonomy."""
    for group in GROUPS:
        for crop in CROPS_BY_GROUP[group]:
            yield crop, group


def crop_row(crop: str, group: str) -> dict[str, object]:
    color = COLOR_OVERRIDES.get(crop, GROUP_COLORS[group])
    include = group != "non_farmland"
    if group == "non_farmland":
        note = NON_FARMLAND_NOTES.get(crop, NOTES["non_farmland"])
    else:
        note = NOTES[group]
    return {
        "crop": crop,
        "group": group,
        "color": color,
        "pattern": GROUP_PATTERNS[group],
        "aliases": ALIASES.get(crop, ""),
        "display_name": DISPLAY_NAMES.get(crop, crop),
        "notes": note,
        "include": "true" if include else "false",
    }
